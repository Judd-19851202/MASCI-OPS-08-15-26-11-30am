        payload = _base_payload(
            "concrete_form",
            mix_design="3000 PSI #57",
            yards_ordered="14.5",
            concrete_vendor="TEST_Cemex",
        )
        r = requests.post(f"{BASE_URL}/api/qaqc-inspections", json=payload, timeout=20)
        assert r.status_code == 200, r.text
        body = r.json()
        assert body["inspection_kind"] == "concrete_form"
        assert body["mix_design"] == "3000 PSI #57"
        assert body["yards_ordered"] == "14.5"
