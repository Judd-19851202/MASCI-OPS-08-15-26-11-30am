class TestStatsAndDelete:
    def test_stats_endpoint(self, admin_headers):
        r = requests.get(
            f"{BASE_URL}/api/admin/qaqc-inspections/stats",
            headers=admin_headers,
            timeout=15,
        )
        assert r.status_code == 200, r.text
        body = r.json()
        assert "total" in body and isinstance(body["total"], int)
        assert "by_kind" in body and isinstance(body["by_kind"], list)
        kinds = {row["kind"] for row in body["by_kind"]}
        assert {"concrete_form", "rebar", "subcontractor_work"}.issubset(kinds)

    def test_delete_record(self, admin_headers):
        # Create a throwaway record explicitly for delete
        payload = _base_payload("rebar")
        r = requests.post(f"{BASE_URL}/api/qaqc-inspections", json=payload, timeout=20)
        assert r.status_code == 200
        rid = r.json()["id"]

        d = requests.delete(
            f"{BASE_URL}/api/qaqc-inspections/{rid}",
            headers=admin_headers,
            timeout=15,
        )
        assert d.status_code == 200
        assert d.json().get("deleted") is True

        # Verify removal — GET should 404
        g = requests.get(
            f"{BASE_URL}/api/qaqc-inspections/{rid}",
            headers=admin_headers,
            timeout=10,
        )
        assert g.status_code == 404
